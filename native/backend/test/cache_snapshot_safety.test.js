'use strict'
const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('fs')
const path = require('path')
const crypto = require('crypto')
const { tmpdir } = require('./fixtures')
const { snapshotFile } = require('../lib/cache')
const sha = bytes => crypto.createHash('sha256').update(bytes).digest('hex')
function fixture(t) {
  const root = tmpdir(), file = path.join(root, 'original.jpg'), stage = path.join(root, 'private'), uuid = '12345678-1234-1234-1234-123456789abc'
  fs.mkdirSync(stage); fs.writeFileSync(file, 'original verified source')
  t.after(() => fs.rmSync(root, { recursive: true, force: true }))
  t.mock.method(crypto, 'randomUUID', () => uuid)
  return { root, file, stage, target: path.join(stage, `${uuid}.jpg`), digest: sha(fs.readFileSync(file)) }
}
test('a failed exclusive snapshot creation preserves a pre-existing destination', async t => {
  const f = fixture(t), manual = Buffer.from('existing unrelated customer snapshot')
  fs.writeFileSync(f.target, manual)
  await assert.rejects(snapshotFile(f.file, f.stage, f.digest))
  assert.equal(fs.existsSync(f.target), true, 'EEXIST must never authorize deleting the existing destination')
  assert.deepEqual(fs.readFileSync(f.target), manual)
})
test('a substituted snapshot name cannot chmod or unlink an unrelated customer file', async t => {
  const f = fixture(t), customer = path.join(f.root, 'customer.jpg'), displaced = path.join(f.root, 'captured-snapshot.jpg')
  fs.writeFileSync(customer, 'untouched customer bytes', { mode: 0o600 })
  const chmod = fs.promises.chmod.bind(fs.promises), open = fs.promises.open.bind(fs.promises)
  let injected = false
  const swap = () => { if (!injected) { injected = true; fs.renameSync(f.target, displaced); fs.symlinkSync(customer, f.target) } }
  t.mock.method(fs.promises, 'chmod', async (file, mode) => { if (file === f.target) swap(); return chmod(file, mode) })
  t.mock.method(fs.promises, 'open', async (file, ...args) => {
    const handle = await open(file, ...args)
    if (file === f.target) { const method = handle.chmod.bind(handle); handle.chmod = async mode => { swap(); return method(mode) } }
    return handle
  })
  await assert.rejects(snapshotFile(f.file, f.stage, f.digest), /snapshot|changed|preserv|protect/i)
  assert.equal(injected, true)
  assert.equal(fs.statSync(customer).mode & 0o777, 0o600, 'chmod must target the verified open descriptor')
  assert.equal(fs.readFileSync(customer, 'utf8'), 'untouched customer bytes')
  assert.equal(fs.lstatSync(f.target).isSymbolicLink(), true, 'the substituted name belongs to the external writer')
  assert.equal(fs.readFileSync(displaced, 'utf8'), fs.readFileSync(f.file, 'utf8'))
})

test('a partial snapshot write retains its generated bytes without deleting the source', async t => {
  const f = fixture(t), open = fs.promises.open.bind(fs.promises)
  t.mock.method(fs.promises, 'open', async (file, ...args) => {
    const handle = await open(file, ...args)
    if (file === f.target && typeof args[0] === 'number' && args[0] & fs.constants.O_CREAT) {
      const write = handle.write.bind(handle)
      handle.write = async (buffer, offset, length, position) => { await write(buffer, offset, 1, position); throw Object.assign(new Error('ENOSPC partial snapshot'), { code: 'ENOSPC' }) }
    }
    return handle
  })
  const error = await snapshotFile(f.file, f.stage, f.digest).then(() => null, e => e)
  assert.equal(error.code, 'SNAPSHOT_PRESERVED'); assert.equal(error.sourceCode, 'ENOSPC')
  assert.ok(error.retainedPath); assert.equal(fs.readFileSync(error.retainedPath, 'utf8'), 'o')
  assert.equal(fs.readFileSync(f.file, 'utf8'), 'original verified source'); assert.deepEqual(fs.readdirSync(f.stage), [])
})

test('a manual edit of the generated snapshot is retained for review', async t => {
  const f = fixture(t), open = fs.promises.open.bind(fs.promises), manual = Buffer.from('manual private snapshot edit')
  t.mock.method(fs.promises, 'open', async (file, ...args) => {
    const handle = await open(file, ...args)
    if (file === f.target && typeof args[0] === 'number' && args[0] & fs.constants.O_CREAT) {
      const chmod = handle.chmod.bind(handle)
      handle.chmod = async mode => { await chmod(0o600); fs.writeFileSync(f.target, manual); return chmod(mode) }
    }
    return handle
  })
  const error = await snapshotFile(f.file, f.stage, f.digest).then(() => null, e => e)
  assert.equal(error.code, 'SNAPSHOT_PRESERVED'); assert.deepEqual(fs.readFileSync(error.retainedPath), manual)
  assert.equal(fs.readFileSync(f.file, 'utf8'), 'original verified source')
})

test('snapshot copies stream bounded allocations and start read-only before the first write', async t => {
  const f = fixture(t), bytes = Buffer.alloc(3 * 1024 * 1024 + 1, 0x51)
  fs.writeFileSync(f.file, bytes)
  const alloc = Buffer.alloc, open = fs.promises.open.bind(fs.promises)
  let written = 0
  t.mock.method(Buffer, 'alloc', (size, ...args) => { assert.ok(size <= 1024 * 1024); return alloc(size, ...args) })
  t.mock.method(fs.promises, 'open', async (file, ...args) => {
    const handle = await open(file, ...args)
    if (file === f.target && typeof args[0] === 'number' && args[0] & fs.constants.O_CREAT) {
      const write = handle.write.bind(handle)
      handle.write = async (...call) => { assert.equal((await handle.stat()).mode & 0o222, 0); written++; return write(...call) }
    }
    return handle
  })
  const target = await snapshotFile(f.file, f.stage, sha(bytes))
  assert.equal(sha(fs.readFileSync(target)), sha(bytes)); assert.ok(written >= 4)
})
