test('snapshot copies stream bounded allocations and start read-only before the first write', async (t) => {
  const f = fixture(t),
    bytes = Buffer.alloc(3 * 1024 * 1024 + 1, 0x51)
  fs.writeFileSync(f.file, bytes)
  const alloc = Buffer.alloc,
    open = fs.promises.open.bind(fs.promises)
  let written = 0
  t.mock.method(Buffer, 'alloc', (size, ...args) => {
    assert.ok(size <= 1024 * 1024)
    return alloc(size, ...args)
  })
  t.mock.method(fs.promises, 'open', async (file, ...args) => {
    const handle = await open(file, ...args)
    if (file === f.target && typeof args[0] === 'number' && args[0] & fs.constants.O_CREAT) {
      const write = handle.write.bind(handle)
      handle.write = async (...call) => {
        assert.equal((await handle.stat()).mode & 0o222, 0)
        written++
        return write(...call)
      }
    }
    return handle
  })
  const target = await snapshotFile(f.file, f.stage, sha(bytes))
  assert.equal(sha(fs.readFileSync(target)), sha(bytes))
  assert.ok(written >= 4)
})

