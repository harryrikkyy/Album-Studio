test('both close failures preserve the primary write error and its concrete recovery path', async (t) => {
  const f = fixture(t),
    open = fs.promises.open.bind(fs.promises)
  let sourceCloses = 0,
    destinationCloses = 0
  t.mock.method(fs.promises, 'open', async (file, ...args) => {
    const handle = await open(file, ...args)
    if (file === f.file) {
      const close = handle.close.bind(handle)
      handle.close = async () => {
        sourceCloses++
        await close()
        throw Object.assign(new Error('EIO source descriptor close'), { code: 'EIO' })
      }
    }
    if (file === f.target && typeof args[0] === 'number' && args[0] & fs.constants.O_CREAT) {
      const close = handle.close.bind(handle),
        write = handle.write.bind(handle)
      handle.close = async () => {
        destinationCloses++
        await close()
        throw Object.assign(new Error('EBADF destination descriptor close'), { code: 'EBADF' })
      }
      handle.write = async (buffer, offset, length, position) => {
        await write(buffer, offset, 1, position)
        throw Object.assign(new Error('ENOSPC primary partial snapshot'), { code: 'ENOSPC' })
      }
    }
    return handle
  })
  const error = await snapshotFile(f.file, f.stage, f.digest).then(
    () => null,
    (e) => e,
  )
  assert.equal(sourceCloses, 1)
  assert.equal(destinationCloses, 1, 'every opened descriptor receives its close attempt')
  assert.equal(error.code, 'SNAPSHOT_PRESERVED')
  assert.equal(error.sourceCode, 'ENOSPC')
  assert.equal(error.cause.code, 'ENOSPC')
  assert.match(error.message, /ENOSPC primary/)
  assert.match(error.message, /EIO source/)
  assert.match(error.message, /EBADF destination/)
  assert.equal(fs.readFileSync(error.snapshotPath, 'utf8'), 'o')
  assert.equal(fs.readFileSync(f.file, 'utf8'), 'original verified source')
})

for (const which of ['source', 'destination', 'both'])
  test(`a verified copy with ${which} close failure reports its existing protected snapshot`, async (t) => {
    const f = fixture(t),
      open = fs.promises.open.bind(fs.promises)
    let sourceCloses = 0,
      destinationCloses = 0
    t.mock.method(fs.promises, 'open', async (file, ...args) => {
      const handle = await open(file, ...args)
      if (file === f.file) {
        const close = handle.close.bind(handle)
        handle.close = async () => {
          sourceCloses++
          await close()
          if (which !== 'destination')
            throw Object.assign(new Error('EIO source close after successful copy'), { code: 'EIO' })
        }
      }
      if (file === f.target && typeof args[0] === 'number' && args[0] & fs.constants.O_CREAT) {
        const close = handle.close.bind(handle)
        handle.close = async () => {
          destinationCloses++
          await close()
          if (which !== 'source')
            throw Object.assign(new Error('EBADF destination close after successful copy'), { code: 'EBADF' })
        }
      }
      return handle
    })
    const error = await snapshotFile(f.file, f.stage, f.digest).then(
      () => null,
      (e) => e,
    )
    assert.ok(error)
    assert.equal(sourceCloses, 1)
    assert.equal(destinationCloses, 1)
    assert.equal(error.code, 'SNAPSHOT_PRESERVED')
    assert.equal(error.snapshotPath, f.target)
    assert.equal(fs.existsSync(error.snapshotPath), true)
    assert.equal(sha(fs.readFileSync(error.snapshotPath)), f.digest)
    assert.equal(fs.statSync(error.snapshotPath).mode & 0o222, 0)
    assert.equal(error.sourceCode, which === 'destination' ? 'EBADF' : 'EIO')
    if (which === 'both') {
      assert.match(error.message, /EIO source/)
      assert.match(error.message, /EBADF destination/)
    }
  })
