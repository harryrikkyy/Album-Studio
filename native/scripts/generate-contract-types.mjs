#!/usr/bin/env node
// Deterministic declarations from the canonical schema/manifest. --check never writes.
import fs from 'node:fs'
import path from 'node:path'
import crypto from 'node:crypto'
import { fileURLToPath } from 'node:url'
const DEFAULT_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..')
const hash = bytes => crypto.createHash('sha256').update(bytes).digest('hex')
const quote = value => JSON.stringify(value)
export function generateContractTypes(root = DEFAULT_ROOT) {
  const folder = path.join(root, 'native/contracts'), schemaBytes = fs.readFileSync(path.join(folder, 'album-studio.schema.json')), manifestBytes = fs.readFileSync(path.join(folder, 'contract-manifest.json'))
  const schema = JSON.parse(schemaBytes), manifest = JSON.parse(manifestBytes)
  const refType = ref => {
    if (!/^#\/\$defs\/[^/]+$/.test(ref)) throw Error(`Only canonical definition references can be generated: ${ref}`)
    const key = ref.slice('#/$defs/'.length).replace(/~1/g, '/').replace(/~0/g, '~')
    if (!Object.hasOwn(schema.$defs, key)) throw Error(`Unresolved canonical definition: ${ref}`)
    if (key === 'JsonValue') return 'JsonValue'
    return `Definitions[${quote(key)}]`
  }
  const type = value => {
    if (value === true) throw Error('Unchecked open schemas cannot generate canonical types.')
    if (value === false) return 'never'
    if (value.$ref) return refType(value.$ref)
    if (Object.hasOwn(value, 'const')) return quote(value.const)
    if (value.enum) return value.enum.map(quote).join(' | ') || 'never'
    if (value.anyOf || value.oneOf) return (value.anyOf || value.oneOf).map(item => `(${type(item)})`).join(' | ')
    if (value.type === 'null') return 'null'
    if (value.type === 'boolean') return 'boolean'
    if (value.type === 'number' || value.type === 'integer') return 'number'
    if (value.type === 'string') return 'string'
    if (value.type === 'array') return `Array<${type(value.items)}>`
    if (value.type === 'object') {
      const properties = Object.entries(value.properties || {}).sort(([a], [b]) => a.localeCompare(b)), required = new Set(value.required || [])
      const fields = properties.map(([key, item]) => `${quote(key)}${required.has(key) ? '' : '?'}: ${type(item)};`)
      if (value.additionalProperties && typeof value.additionalProperties === 'object') fields.push(`[key: string]: ${type(value.additionalProperties)} | undefined;`)
      else if (value.additionalProperties === true) throw Error('Unchecked object extensions cannot generate canonical types.')
      return fields.length ? `{ ${fields.join(' ')} }` : 'Record<string, never>'
    }
    throw Error(`Unsupported canonical schema shape: ${JSON.stringify(value)}`)
  }
  const definitions = Object.entries(schema.$defs).sort(([a], [b]) => a.localeCompare(b))
  const lines = ['// Generated by native/scripts/generate-contract-types.mjs. Do not edit.', `// schema-sha256: ${hash(schemaBytes)}`, `// manifest-sha256: ${hash(manifestBytes)}`, '// Runtime validators enforce bounds/finite values; TypeScript alone does not.', '', `export type JsonValue = ${type(schema.$defs.JsonValue)}`, '', 'export interface Definitions {']
  for (const [name, definition] of definitions) lines.push(`  ${quote(name)}: ${name === 'JsonValue' ? 'JsonValue' : type(definition)}`)
  lines.push('}', '')
  for (const [name] of definitions) if (/^[A-Za-z_$][\w$]*$/.test(name) && !['JsonValue', 'RequestEnvelope', 'ReplyEnvelope', 'EventEnvelope'].includes(name)) lines.push(`export type ${name} = Definitions[${quote(name)}]`)
  lines.push('', 'export interface MethodContracts {')
  for (const [name, method] of Object.entries(manifest.methods).sort(([a], [b]) => a.localeCompare(b))) lines.push(`  ${quote(name)}: { params: ${type(method.params)}; result: ${type(method.result)} }`)
  lines.push('}', 'export type MethodName = keyof MethodContracts', 'export type MethodParams<M extends MethodName> = MethodContracts[M]["params"]', 'export type MethodResult<M extends MethodName> = MethodContracts[M]["result"]', '', 'export interface EventContracts {')
  for (const [name, event] of Object.entries(manifest.events).sort(([a], [b]) => a.localeCompare(b))) lines.push(`  ${quote(name)}: ${type(event.data)}`)
  lines.push('}', 'export type EventName = keyof EventContracts', 'export type EventData<E extends EventName> = EventContracts[E]', 'export type RequestEnvelope<M extends MethodName = MethodName> = { id: number; method: M; params?: MethodParams<M> }', 'export type ReplyEnvelope<M extends MethodName = MethodName> = { id: number; ok: true; result: MethodResult<M> } | (Definitions["FailureReply"])', 'export type EventEnvelope<E extends EventName = EventName> = { event: E; data?: EventData<E> }', '')
  return lines.join('\n')
}
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    let root = DEFAULT_ROOT, check = false
    for (let i = 2; i < process.argv.length; i++) {
      if (process.argv[i] === '--check') check = true
      else if (process.argv[i] === '--root' && process.argv[i + 1]) root = path.resolve(process.argv[++i])
      else throw Error(`Unknown contract generator option: ${process.argv[i]}`)
    }
    const file = path.join(root, 'native/contracts/types.ts'), expected = generateContractTypes(root)
    if (check) {
      if (!fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== expected) throw Error('Canonical types.ts differs from the schema/manifest. Run node native/scripts/generate-contract-types.mjs and review the generated diff.')
      process.stdout.write('Canonical contract types match the schema and manifest.\n')
    } else { fs.writeFileSync(file, expected); process.stdout.write(`${file}\n`) }
  } catch (error) { process.stderr.write(`${error.message}\n`); process.exitCode = 1 }
}
